// Real signup/session/verification with a local, network-blocking email provider.
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { writeFile } from "node:fs/promises";
import { withLocalSmokeFixture } from "./local-smoke-fixture.mjs";
import { poll, withRealBrowser } from "./real-browser-fixture.mjs";
const run = promisify(execFile);
const password = "Disposable-signup-password-92!";
await withLocalSmokeFixture(async ({ origin, orgId, operatorEmail, operatorPassword, configureEmail, capturedEmails, stopServer, queryFixture }) => {
  const emailLink = async (email, returnTo) => {
    const messages = await capturedEmails();
    const message = messages.filter(message => message.to === email && message.delivered).at(-1);
    assert.ok(message, "Captured successful verification email");
    const link = message.html.match(/href="([^"]*\/api\/auth\/verify-email[^\"]*)"/)?.[1]?.replaceAll("&amp;", "&");
    assert.ok(link, "Actual verification link generated by Better Auth");
    const url = new URL(link); assert.equal(url.origin, origin);
    const callback = new URL(url.searchParams.get("callbackURL"), origin);
    assert.equal(callback.pathname, "/verify-email");
    assert.equal(callback.searchParams.get("returnTo"), returnTo);
    return link;
  };
  await withRealBrowser({ origin }, async ({ page, evaluate }) => {
    await page("Page.enable");
    await page("Page.addScriptToEvaluateOnNewDocument", { source: `
      window.signupErrors=[];window.signupWrites=0;window.signinWrites=0;window.signupMode='live';window.signupDocument=crypto.randomUUID();
      addEventListener('error',event=>window.signupErrors.push(event.message));
      addEventListener('unhandledrejection',event=>window.signupErrors.push(String(event.reason)));
      const original=window.fetch;
      window.fetch=async(input,options)=>{
        const url=input instanceof Request?input.url:String(input);
        if(url.endsWith('/api/auth/sign-up/email')){
          window.signupWrites++;
          const response=await original(input,options);
          if(window.signupMode==='lose-save'){
            const body=await response.text();window.signupSaved=response.status;
            return new Promise(resolve=>{window.releaseSignup=()=>resolve(new Response(body,{status:response.status,headers:response.headers}));});
          }
          return response;
        }
        if(url.endsWith('/api/auth/sign-in/email'))window.signinWrites++;
        return original(input,options);
      };` });
    const check = (expression, label, timeout) => poll(() => evaluate(expression), label, timeout);
    const text = value => check(`document.body?.innerText.includes(${JSON.stringify(value)})`, value).catch(async error => { console.log(JSON.stringify({ expected: value, page: await evaluate("document.body?.innerText"), path: await evaluate("location.pathname") })); throw error; });
    const open = path => page("Page.navigate", { url: new URL(path, origin).toString() });
    const noErrors = async () => assert.deepEqual(await evaluate("window.signupErrors"), []);
    const click = async name => {
      const point = await poll(() => evaluate(`(async()=>{
        const node=[...document.querySelectorAll('button,a')].find(node=>(node.textContent.trim()===${JSON.stringify(name)}||node.getAttribute('aria-label')===${JSON.stringify(name)})&&!node.disabled);
        if(!node)return null;node.scrollIntoView({block:'center'});await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
        const r=node.getBoundingClientRect(),x=r.x+r.width/2,y=r.y+r.height/2;return node.contains(document.elementFromPoint(x,y))?{x,y}:null;
      })()`), `reachable ${name}`);
      await page("Input.dispatchMouseEvent", { type: "mousePressed", ...point, button: "left", clickCount: 1 });
      await page("Input.dispatchMouseEvent", { type: "mouseReleased", ...point, button: "left", clickCount: 1 });
    };
    const fill = (selector, value) => evaluate(`(()=>{const node=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(node,${JSON.stringify(value)});node.dispatchEvent(new Event('input',{bubbles:true}));return true;})()`);
    const fresh = async path => { await noErrors(); await page("Network.clearBrowserCookies"); await open(path); };
    const readyForm = async () => {
      await check("!!document.querySelector('#password')", "auth form");
      await click("Show password"); await check("document.querySelector('#password').type==='text'", "hydrated password control");
      await click("Hide password"); await check("document.querySelector('#password').type==='password'", "password hidden");
    };
    const signup = async email => {
      await check("!!document.querySelector('#name')", "signup form"); await readyForm();
      await fill("#name", "Signup fixture"); await fill("#email", email); await fill("#password", password); await click("Create account");
    };
    const geometry = async name => {
      for (const [width, height] of [[320,568],[768,1024],[1440,900]]) {
        await page("Emulation.setDeviceMetricsOverride", { width, height, deviceScaleFactor: 1, mobile: false });
        await check(`(async()=>{
          const node=[...document.querySelectorAll('button,a')].find(node=>node.textContent.trim()===${JSON.stringify(name)}&&!node.disabled);
          if(!node)return false;node.scrollIntoView({block:'center'});await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
          for(let parent=node;parent;parent=parent.parentElement){if(parent.getAnimations().some(animation=>animation.playState==='running'))return false;}
          const r=node.getBoundingClientRect();return document.documentElement.scrollWidth<=innerWidth+1&&r.height>=44&&r.width>=44&&r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight&&node.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2));
        })()`, `${name} at ${width}`);
        if (width === 320) await writeFile(`/tmp/showpilot-signup-${name.replaceAll(" ", "-").toLowerCase()}-320.png`, Buffer.from((await page("Page.captureScreenshot", { format: "png" })).data, "base64"));
      }
    };
    // Anonymous deep navigation survives login, including room and fragment.
    const deep = `/${orgId}/chat?room=planning#signup-proof`;
    await open(deep); await check("!!document.querySelector('#email')", "deep-link login");
    assert.equal(await evaluate("new URL(location.href).searchParams.get('returnTo')+location.hash"), deep);
    await readyForm(); await fill("#email", operatorEmail); await fill("#password", operatorPassword); await click("Sign in");
    await text("Planning Room");
    assert.equal(await evaluate("location.pathname+location.search+location.hash"), deep); await noErrors();
    await open("/login?returnTo=" + encodeURIComponent(deep)); await text("Planning Room");
    assert.equal(await evaluate("location.pathname+location.search+location.hash"), deep); await noErrors();
    await open("/unavailable-fixture/chat"); await text("We couldn't load this page. Try again, or return to your workspace to continue.");
    assert.equal(await evaluate("location.pathname"), "/unavailable-fixture/chat"); await noErrors();
    // Email provider rejects delivery after the account has already been saved.
    await configureEmail("fail");
    await fresh("/login?signup=1&returnTo=" + encodeURIComponent("/setup?mode=new"));
    await signup("failed-delivery@display-smoke.invalid"); await text("Check your inbox");
    assert.equal((await capturedEmails()).filter(message => !message.delivered && message.to === "failed-delivery@display-smoke.invalid").length, 1, "Actual provider failure after account creation");
    assert.equal(await evaluate("location.pathname"), "/verify-email");
    assert.equal(await evaluate("new URL(location.href).searchParams.get('returnTo')"), "/setup?mode=new");
    assert.equal(await evaluate("[...document.querySelectorAll('a')].some(node=>node.textContent==='Continue')"), false);
    await click("Resend verification email"); await text("We couldn't confirm that the email was sent.");
    await geometry("Retry sending verification email");
    await configureEmail("success"); await click("Retry sending verification email"); await text("Verification email sent. Check your inbox.");
    await noErrors(); await open(await emailLink("failed-delivery@display-smoke.invalid", "/setup?mode=new")); await text("Email verified");
    await click("Continue"); await check("location.pathname==='/setup'&&new URL(location.href).searchParams.get('mode')==='new'&&!!document.querySelector('#organization-name')", "verified setup destination"); await noErrors();
    // A normal signup always lands on the interstitial, even with a deep return.
    await fresh("/login?signup=1&returnTo=" + encodeURIComponent("/delete-account"));
    await signup("successful-signup@display-smoke.invalid"); await text("Check your inbox");
    assert.equal(await evaluate("location.pathname"), "/verify-email");
    await geometry("I've verified my email"); await noErrors();
    const successLink = await emailLink("successful-signup@display-smoke.invalid", "/delete-account");
    // A fresh browser session follows the real email link and retains its destination.
    await fresh(successLink); await text("Email verified"); await click("Continue");
    await check("location.pathname==='/delete-account'", "verified account destination"); await noErrors();
    // A successful response can be lost after account/session creation.
    await fresh("/login?signup=1");
    await check("!!document.querySelector('#name')", "third signup form");
    await evaluate("window.signupMode='lose-save'"); await signup("lost-signup@display-smoke.invalid");
    await check("window.signupSaved===200", "actual committed signup before withheld reply");
    await text("Your account may already exist.");
    assert.equal(await evaluate("window.signupWrites"), 1);
    assert.equal(await evaluate("document.querySelector('#email').value"), "lost-signup@display-smoke.invalid");
    assert.equal(await evaluate("document.querySelector('#password').value"), password);
    await geometry("Sign in to check account");
    const documentId = await evaluate("window.signupDocument");
    await evaluate("window.releaseSignup();true");
    assert.equal(await evaluate("window.signupDocument"), documentId);
    assert.equal(await evaluate("location.pathname"), "/login");
    await click("Sign in to check account"); await fill("#password", password); await click("Sign in"); await text("Check your inbox"); await noErrors();
    // Signed-out status recovery returns to verification rather than losing context.
    await fresh("/verify-email?returnTo=" + encodeURIComponent("/setup?mode=new")); await text("Sign in to check verification");
    await click("Sign in"); await check("!!document.querySelector('#email')", "verification recovery login");
    assert.equal(await evaluate("new URL(location.href).searchParams.get('verify')"), "1");
    await readyForm(); await fill("#email", "lost-signup@display-smoke.invalid"); await fill("#password", password); await click("Sign in"); await text("Check your inbox");
    assert.equal(await evaluate("new URL(location.href).searchParams.get('returnTo')"), "/setup?mode=new"); await noErrors();
  });
  // Required login layout regression covers both modes, tablets, short windows,
  // 27-inch and ultrawide widths against this exact compiled Worker.
  const responsive = await run(process.execPath, [new URL("./smoke-login-responsive.mjs", import.meta.url).pathname, origin], { timeout: 180_000, maxBuffer: 2_000_000 });
  console.log(responsive.stdout);
  const messages = await capturedEmails();
  assert.equal(messages.filter(message => !message.delivered).length, 2);
  assert.equal(messages.filter(message => message.delivered).length, 3);
  await stopServer();
  const users = await queryFixture("SELECT email,emailVerified FROM user WHERE email IN ('failed-delivery@display-smoke.invalid','successful-signup@display-smoke.invalid','lost-signup@display-smoke.invalid') ORDER BY email");
  assert.deepEqual(users, [{ email: "failed-delivery@display-smoke.invalid", emailVerified: 1 }, { email: "lost-signup@display-smoke.invalid", emailVerified: 0 }, { email: "successful-signup@display-smoke.invalid", emailVerified: 1 }]);
  assert.equal((await queryFixture("SELECT COUNT(*) AS count FROM account WHERE userId IN (SELECT id FROM user WHERE email IN ('failed-delivery@display-smoke.invalid','successful-signup@display-smoke.invalid','lost-signup@display-smoke.invalid'))"))[0].count, 3);
  assert.equal((await queryFixture("SELECT COUNT(*) AS count FROM member WHERE userId IN (SELECT id FROM user WHERE email IN ('failed-delivery@display-smoke.invalid','successful-signup@display-smoke.invalid','lost-signup@display-smoke.invalid'))"))[0].count, 0);
  console.log(JSON.stringify({ passed: true, actualSignupAndVerification: true, capturedEmailOnly: true, providerFailureRecovery: true, lostAcknowledgementRecovery: true, deepLinkAndVerificationDestination: true, unauthorizedWorkspaceNoLoop: true, finalD1Verified: true, responsiveModesAndViewports: 24 }));
}, { captureEmail: true });
