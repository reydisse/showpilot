// Built UI -> authenticated commands -> real timecode relay, including stale drafts.
import assert from "node:assert/strict";
import { withLocalSmokeFixture } from "./local-smoke-fixture.mjs";
import { poll } from "./real-browser-fixture.mjs";

await withLocalSmokeFixture(async ({ origin, orgId, browser, operatorEmail, operatorPassword, operatorCookie, stopServer, startServer }) => {
  const click = name => browser("find", "role", "button", "click", "--name", name, "--exact");
  const evaluate = async expression => (await browser("eval", expression)).result;
  const form = 'form:has(input[placeholder="00:05:00:00"])';
  const dialog = '[role="dialog"]';
  const fillDialog = async (label, value) => {
    const id = await evaluate(`Array.from(document.querySelectorAll('${dialog} label')).find(label => label.textContent.trim() === ${JSON.stringify(label)})?.htmlFor`);
    assert.ok(id, `Missing label ${label}`);
    await browser("fill", `[id=${JSON.stringify(id)}]`, value);
  };
  const events = async () => {
    const response = await fetch(`${origin}/api/timecode/${orgId}/events?showId=smoke-show`, { headers: { Cookie: operatorCookie } });
    assert.equal(response.status, 200); return response.json();
  };
  await browser("open", `${origin}/login`);
  await browser("fill", "#email", operatorEmail);
  await browser("fill", "#password", operatorPassword);
  await click("Sign in");
  await browser("wait", "--url", `**/${orgId}/**`);
  await browser("open", `${origin}/${orgId}/timecode`);
  await browser("wait", "text=Start Internal Generator");
  await browser("fill", `${form} input[placeholder="00:05:00:00"]`, "00:01:00:00");
  await browser("select", `${form} select >> nth=0`, "lyrics-clear");
  await browser("find", "label", "Label", "fill", "Edit rehearsal");
  await click("Add Event");
  const original = await poll(async () => (await events()).find(event => event.label === "Edit rehearsal"), "saved initial cue");
  await click("Edit Edit rehearsal");
  await fillDialog("Timecode (HH:MM:SS:FF)", "99:99:99:99");
  assert.equal(await evaluate(`document.querySelector('${dialog} button[type=submit]').disabled`), true);
  await browser("wait", "text=Enter a valid timecode for 30 fps NDF.");
  await fillDialog("Timecode (HH:MM:SS:FF)", "00:02:00:00");
  await fillDialog("Label", "Edited cue");
  await fillDialog("Tolerance (frames)", "7");
  await fillDialog("Cue lead (ms)", "100");
  await browser("set", "viewport", "320", "780");
  const size = await evaluate(`(() => { const el = document.querySelector('${dialog}'); const box = el.getBoundingClientRect(); return { fits: el.scrollWidth <= el.clientWidth + 1, left: box.left, right: box.right, viewport: innerWidth }; })()`);
  assert.equal(size.fits, true); assert.ok(size.left >= 0 && size.right <= size.viewport + 1);
  await browser("screenshot", "/tmp/showpilot-cue-edit-320.png");
  await click("Save changes");
  await browser("wait", "--fn", `document.querySelector('${dialog}') === null`);
  const edited = (await events())[0];
  assert.equal(edited.id, original.id); assert.equal(edited.label, "Edited cue");
  assert.equal(edited.triggerFrame, 3600); assert.equal(edited.dispatchFrame, 3597); assert.equal(edited.toleranceFrames, 7);
  assert.notEqual(edited.editRevision, original.editRevision);
  await browser("set", "viewport", "1440", "900");
  await click("Fire Edited cue");
  const fired = await poll(async () => { const event = (await events())[0]; return event.fired && event; }, "cue acknowledgement");
  await click("Edit Edited cue");
  await fillDialog("Label", "Edited after firing");
  await click("Save changes");
  await browser("wait", "--fn", `document.querySelector('${dialog}') === null`);
  const completed = (await events())[0];
  assert.equal(completed.executionId, fired.executionId); assert.equal(completed.fired, true); assert.equal(completed.executionAttempts, 1);
  await click("Edit Edited after firing");
  await fillDialog("Label", "My unsaved draft");
  const result = await evaluate(`fetch(${JSON.stringify(`/api/timecode/${orgId}/command?showId=smoke-show`)}, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(${JSON.stringify({ action: "update-event", payload: { id: original.id, updates: { label: "Concurrent edit" } } })}) }).then(async response => ({ status: response.status, body: await response.json() }))`);
  assert.equal(result.status, 200, JSON.stringify(result.body));
  await browser("wait", "text=This cue or the frame rate changed.");
  assert.equal(await evaluate(`document.querySelector('${dialog} input[maxlength="200"]').value`), "My unsaved draft");
  assert.equal(await evaluate(`document.querySelector('${dialog} fieldset').disabled`), true);
  await browser("screenshot", "/tmp/showpilot-cue-edit-stale.png");
  await click("Reload latest cue");
  assert.equal(await evaluate(`document.querySelector('${dialog} input[maxlength="200"]').value`), "Concurrent edit");
  await fillDialog("Label", "Offline draft");
  await stopServer();
  await browser("wait", "--fn", `document.querySelector('${dialog} fieldset').disabled`);
  assert.equal(await evaluate(`document.querySelector('${dialog} input[maxlength="200"]').value`), "Offline draft");
  await startServer();
  await browser("wait", "--fn", `document.querySelector('${dialog} fieldset').disabled === false`);
  await click("Save changes");
  await browser("wait", "--fn", `document.querySelector('${dialog}') === null`);
  const reconnected = (await events())[0];
  assert.equal(reconnected.label, "Offline draft"); assert.equal(reconnected.fired, true); assert.equal(reconnected.executionId, fired.executionId);
  await browser("fill", `${form} input[placeholder="00:05:00:00"]`, "00:03:00:00");
  await browser("select", `${form} select >> nth=0`, "custom-webhook");
  await browser("find", "label", "Webhook URL", "fill", "https://127.0.0.1/private");
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(form)}).querySelector('button[type=submit]').disabled`), true);
  await browser("find", "label", "Webhook URL", "fill", "https://example.com/hook");
  await click("Add Event");
  await poll(async () => (await events()).some(event => event.action === "custom-webhook" && event.payload.url === "https://example.com/hook"), "validated webhook cue saved");
  console.log(JSON.stringify({ passed: true, cueIdPreserved: original.id, executionHistoryPreserved: true, staleDraftPreserved: true, offlineDraftPreserved: true, narrowDialogFits: true }));
});
