/**
 * Runs asynchronous state transitions one at a time without making callers
 * manage a shared lock. A rejected operation releases the next waiter.
 */
export class SerialCommandExecutor {
  private tail: Promise<void> = Promise.resolve();

  async run<T>(operation: () => Promise<T>): Promise<T> {
    const previous = this.tail;
    let release!: () => void;
    this.tail = new Promise<void>((resolve) => {
      release = resolve;
    });
    await previous;
    try {
      return await operation();
    } finally {
      release();
    }
  }
}
